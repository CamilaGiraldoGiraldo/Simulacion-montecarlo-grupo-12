# Posiciones de los puntos en una cuadrícula 3x3 (0 = arriba izquierda, 8 = abajo derecha)
PUNTOS_DADO = {1: [4], 2: [0, 8], 3: [0, 4, 8], 4: [0, 2, 6, 8],
               5: [0, 2, 4, 6, 8], 6: [0, 2, 3, 5, 6, 8]}


def dado_html(valor, conservado=False):
    borde = "#2e7d32" if conservado else "#555"
    grosor = 4 if conservado else 2
    fondo = "#e8f5e9" if conservado else "#ffffff"
    base = (f"width:76px;height:76px;box-sizing:border-box;border:{grosor}px solid {borde};"
            f"border-radius:12px;background:{fondo};")
    if valor is None:
        return (f"<div style='{base}display:flex;align-items:center;justify-content:center;"
                f"font-size:36px;color:#999;font-family:sans-serif'>?</div>")
    punto = "<div style='width:12px;height:12px;border-radius:50%;background:#111;margin:auto'></div>"
    celdas = "".join(punto if i in PUNTOS_DADO[valor] else "<div></div>" for i in range(9))
    return (f"<div style='{base}display:grid;grid-template-columns:repeat(3,1fr);"
            f"grid-template-rows:repeat(3,1fr);padding:8px'>{celdas}</div>")


class JuegoVisual:
    def __init__(self, rng=random, animar=True):
        self.rng = rng
        self.animar = animar
        self.nombres = ("Jugador 1", "Jugador 2")
        self.caja = widgets.VBox()
        display(self.caja)
        self._pantalla_inicio()

    # ---------- Pantalla de inicio ----------
    def _pantalla_inicio(self):
        self.in1 = widgets.Text(value=self.nombres[0], description="Jugador 1:")
        self.in2 = widgets.Text(value=self.nombres[1], description="Jugador 2:")
        btn = widgets.Button(description="Empezar partida", button_style="primary",
                             layout=widgets.Layout(width="200px", height="40px"))
        btn.on_click(self._empezar)
        self.caja.children = [
            widgets.HTML("<h2>Yahtzee para dos jugadores</h2>"
                         "<p>Escribe los nombres y pulsa <b>Empezar partida</b>.</p>"),
            self.in1, self.in2, btn]

    def _empezar(self, _):
        n1 = self.in1.value.strip() or "Jugador 1"
        n2 = self.in2.value.strip() or "Jugador 2"
        if n1 == n2:
            n2 += " (2)"
        self.nombres = (n1, n2)
        self._nueva_partida()

    # ---------- Construcción de la partida ----------
    def _nueva_partida(self):
        self.jugadores = [Jugador(self.nombres[0]), Jugador(self.nombres[1])]
        self.turno = 0
        self.ronda = 1
        self.lanzamiento = 0
        self.dados = []
        self.historial = []

        self.titulo = widgets.HTML()
        self.dados_html = [widgets.HTML(dado_html(None)) for _ in range(NUM_DADOS)]
        self.toggles = []
        for i in range(NUM_DADOS):
            t = widgets.ToggleButton(value=False, description="Conservar", disabled=True,
                                     layout=widgets.Layout(width="84px"))
            t.observe(lambda cambio, i=i: self._pintar_dado(i), names="value")
            self.toggles.append(t)
        fila_dados = widgets.HBox(
            [widgets.VBox([h, t], layout=widgets.Layout(align_items="center", margin="0 8px 0 0"))
             for h, t in zip(self.dados_html, self.toggles)])

        self.info = widgets.HTML()
        self.btn_lanzar = widgets.Button(description="Lanzar", button_style="primary",
                                         layout=widgets.Layout(width="260px", height="40px"))
        self.sel = widgets.Dropdown(options=[], description="Categoría:", disabled=True,
                                    layout=widgets.Layout(width="400px"))
        self.btn_anotar = widgets.Button(description="Anotar", button_style="success",
                                         disabled=True, layout=widgets.Layout(width="140px"))
        self.tabla = widgets.HTML()
        self.hist = widgets.HTML()

        self.btn_lanzar.on_click(self._lanzar)
        self.btn_anotar.on_click(self._anotar)

        self.caja.children = [
            self.titulo, fila_dados, self.info, self.btn_lanzar,
            widgets.HBox([self.sel, self.btn_anotar]), self.tabla, self.hist]
        self._nuevo_turno()

    # ---------- Utilidades ----------
    @property
    def jugador(self):
        return self.jugadores[self.turno]

    def _pintar_dado(self, i):
        valor = self.dados[i] if self.dados else None
        conservado = self.toggles[i].value and 0 < self.lanzamiento < MAX_LANZAMIENTOS
        self.dados_html[i].value = dado_html(valor, conservado)
        self.toggles[i].button_style = "success" if self.toggles[i].value else ""

    def _tabla_html(self, resaltar=True):
        j1, j2 = self.jugadores
        activo = self.turno if resaltar else -1
        col = lambda k: "background:#bbdefb" if k == activo else "background:#ddd"
        filas = ""
        for n, c in enumerate(CATEGORIAS):
            filas += (f"<tr><td>{c}</td>"
                      f"<td align='center'>{j1.puntos.get(c, '-')}</td>"
                      f"<td align='center'>{j2.puntos.get(c, '-')}</td></tr>")
            if n == len(SUPERIORES) - 1:
                filas += (f"<tr style='color:#555'><td><i>Subtotal superior (63 = bono)</i></td>"
                          f"<td align='center'>{j1.subtotal_superior()}/{BONO_SUPERIOR_MIN}</td>"
                          f"<td align='center'>{j2.subtotal_superior()}/{BONO_SUPERIOR_MIN}</td></tr>")
        filas += (f"<tr><td>Bono superior (+{BONO_SUPERIOR})</td>"
                  f"<td align='center'>{j1.bono_superior()}</td>"
                  f"<td align='center'>{j2.bono_superior()}</td></tr>"
                  f"<tr><td>Bonos Yahtzee extra ({BONO_YAHTZEE} c/u)</td>"
                  f"<td align='center'>{BONO_YAHTZEE * j1.bonos_yahtzee}</td>"
                  f"<td align='center'>{BONO_YAHTZEE * j2.bonos_yahtzee}</td></tr>"
                  f"<tr style='font-weight:bold;border-top:2px solid gray'><td>TOTAL</td>"
                  f"<td align='center'>{j1.total()}</td>"
                  f"<td align='center'>{j2.total()}</td></tr>")
        return (f"<table style='border-collapse:collapse;margin-top:10px' border='1' cellpadding='4'>"
                f"<tr><th style='background:#ddd'>Categoría</th>"
                f"<th style='{col(0)}'>{j1.nombre}</th>"
                f"<th style='{col(1)}'>{j2.nombre}</th></tr>{filas}</table>")

    def _historial_html(self):
        if not self.historial:
            return ""
        items = "".join(f"<li>{h}</li>" for h in reversed(self.historial[-6:]))
        return (f"<div style='margin-top:10px;font-size:13px'><b>Últimas jugadas</b>"
                f"<ul style='margin:4px 0'>{items}</ul></div>")

    # ---------- Flujo del juego ----------
    def _nuevo_turno(self):
        self.lanzamiento = 0
        self.dados = []
        for i, t in enumerate(self.toggles):
            t.value = False
            t.disabled = True
            self._pintar_dado(i)
        self.info.value = ("<i>Pulsa <b>Lanzar</b>. Después puedes marcar los dados que quieras "
                           "conservar y relanzar el resto.</i>")
        self.btn_lanzar.disabled = False
        self.btn_lanzar.description = f"Lanzar ({MAX_LANZAMIENTOS} lanzamientos)"
        self.sel.options = []
        self.sel.disabled = True
        self.btn_anotar.disabled = True
        self.titulo.value = (f"<h3>Ronda {self.ronda} de {len(CATEGORIAS)} — "
                             f"Turno de <span style='color:#1a73e8'>{self.jugador.nombre}</span></h3>")
        self.tabla.value = self._tabla_html()
        self.hist.value = self._historial_html()

    def _animar(self, indices):
        """Muestra caras al azar unos instantes (solo efecto visual)."""
        for _ in range(5):
            for i in indices:
                self.dados_html[i].value = dado_html(random.randint(1, CARAS))
            time.sleep(0.06)

    def _lanzar(self, _):
        self.btn_lanzar.disabled = True
        self.btn_anotar.disabled = True
        primero = self.lanzamiento == 0
        conservar = set() if primero else {i for i, t in enumerate(self.toggles) if t.value}

        if self.animar:
            self._animar([i for i in range(NUM_DADOS) if i not in conservar])

        if primero:
            self.dados = lanzar_dados(NUM_DADOS, self.rng)
        else:
            self.dados = relanzar(self.dados, conservar, self.rng)
        self.lanzamiento += 1

        restantes = MAX_LANZAMIENTOS - self.lanzamiento
        for i, t in enumerate(self.toggles):
            if restantes == 0:
                t.value = False
            t.disabled = restantes == 0
            self._pintar_dado(i)

        if restantes == 0:
            self.btn_lanzar.description = "Sin lanzamientos"
        else:
            self.btn_lanzar.disabled = False
            self.btn_lanzar.description = f"Relanzar (quedan {restantes})"

        # Mensajes especiales
        aviso = ""
        if es_yahtzee(self.dados):
            if self.jugador.puntos.get("Yahtzee") == 50:
                aviso = " &nbsp; <b style='color:#c62828'>¡Yahtzee extra! +100 de bono y Joker.</b>"
            elif joker_activo(self.jugador.puntos, self.dados):
                aviso = " &nbsp; <b style='color:#c62828'>¡Yahtzee! Se aplica la regla del Joker.</b>"
            else:
                aviso = " &nbsp; <b style='color:#c62828'>¡YAHTZEE!</b>"
        self.info.value = (f"<div style='font-size:16px'><b>Lanzamiento {self.lanzamiento} "
                           f"de {MAX_LANZAMIENTOS}</b>{aviso}</div>")

        # Categorías ordenadas de mayor a menor puntaje
        permitidas = self.jugador.categorias_permitidas(self.dados)
        permitidas = sorted(permitidas, key=lambda c: -self.jugador.puntaje(self.dados, c))
        self.sel.options = [(f"{c}  →  {self.jugador.puntaje(self.dados, c)} pts", c)
                            for c in permitidas]
        self.sel.disabled = False
        self.btn_anotar.disabled = False

    def _anotar(self, _):
        cat = self.sel.value
        pts = self.jugador.anotar(self.dados, cat)
        self.historial.append(f"Ronda {self.ronda} · {self.jugador.nombre}: "
                              f"{self.dados} → {cat} ({pts} pts)")

        self.turno = 1 - self.turno
        if self.turno == 0:
            self.ronda += 1
        if self.ronda > len(CATEGORIAS):
            self._fin()
        else:
            self._nuevo_turno()

    def _fin(self):
        j1, j2 = self.jugadores
        p1, p2 = j1.total(), j2.total()
        if p1 > p2:
            res = f"¡Gana {j1.nombre}!"
        elif p2 > p1:
            res = f"¡Gana {j2.nombre}!"
        else:
            res = "¡Empate!"
        btn = widgets.Button(description="Nueva partida", button_style="primary",
                             layout=widgets.Layout(width="200px", height="40px"))
        btn.on_click(lambda _: self._pantalla_inicio())
        self.caja.children = [
            widgets.HTML(f"<h2>Fin de la partida</h2><h3>{j1.nombre}: {p1} | "
                         f"{j2.nombre}: {p2}</h3><h2>{res}</h2>"),
            btn,
            widgets.HTML(self._tabla_html(resaltar=False)),
            widgets.HTML(self._historial_html()),
        ]

